// The unblurt logo: a highlighted selection and a text cursor.
// One source of truth for every logo file.  Usage: node brand/logo.mjs
import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const C = { teal: "#0F6B6A", pers: "#FF7A45", cream: "#FBF8F4", ink: "#101010" };

// Drawn on a 256 grid. The I-beam is a filled stem with slimmer rounded cross-bars,
// a little taller than the highlight, as a cursor is in a text field.
const beam = (x, top, bottom, w, color, sw) => {
  const bar = Math.round(sw * 0.8);
  return [
    `<rect x="${x - sw / 2}" y="${top}" width="${sw}" height="${bottom - top}" rx="${sw / 2}" fill="${color}"/>`,
    `<rect x="${x - w}" y="${top}" width="${2 * w}" height="${bar}" rx="${bar / 2}" fill="${color}"/>`,
    `<rect x="${x - w}" y="${bottom - bar}" width="${2 * w}" height="${bar}" rx="${bar / 2}" fill="${color}"/>`,
  ].join("");
};

// Bare mark: highlight pill + cursor. Used next to the wordmark, as the favicon, in the UI.
const bare = (pill = C.pers, cursor = C.teal) => [
  `<rect x="14" y="94" width="156" height="68" rx="22" fill="${pill}"/>`,
  beam(206, 52, 204, 24, cursor, 22),
].join("\n  ");

// Tile contents: faint text lines around the selection, cream cursor.
const tile = () => [
  `<rect x="34" y="62" width="128" height="18" rx="9" fill="${C.cream}" fill-opacity=".32"/>`,
  `<rect x="26" y="100" width="146" height="56" rx="18" fill="${C.pers}"/>`,
  `<rect x="34" y="176" width="84" height="18" rx="9" fill="${C.cream}" fill-opacity=".32"/>`,
  beam(206, 60, 196, 20, C.cream, 18),
].join("\n    ");

const svg = (vb, body) => `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${vb}">\n  ${body}\n</svg>\n`;

const files = {
  "brand/mark.svg": svg("0 0 256 256", bare()),
  "apps/web/assets/mark.svg": svg("0 0 256 256", bare()),
  // macOS-style app icon: 824px squircle-ish tile inside the 1024 canvas.
  "brand/app-icon.svg": svg("0 0 1024 1024",
    `<rect x="100" y="100" width="824" height="824" rx="186" fill="${C.teal}"/>\n  <g transform="translate(206 206) scale(2.4)">\n    ${tile()}\n  </g>`),
  // Tray / menu bar: single colour, macOS treats it as a template image.
  "brand/tray.svg": svg("0 0 256 256", bare("#000", "#000")),
};

for (const [path, data] of Object.entries(files)) {
  writeFileSync(join(root, path), data);
  console.log("wrote", path);
}

// React component for the desktop app, kept in sync with the same geometry.
const tsx = `// Generated by brand/logo.mjs. The unblurt mark: a highlighted selection and a text cursor.
export function Mark({ size = 22 }: { size?: number }) {
  return (
    <svg width={size} height={size} viewBox="0 0 256 256" aria-hidden="true"
      dangerouslySetInnerHTML={{ __html: ${JSON.stringify(bare("var(--persimmon)", "var(--teal)").replace(/\n\s*/g, ""))} }} />
  );
}
`;
writeFileSync(join(root, "apps/desktop/src/components/Mark.tsx"), tsx);
console.log("wrote apps/desktop/src/components/Mark.tsx");
